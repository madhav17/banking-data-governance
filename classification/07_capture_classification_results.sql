/*==============================================================================
 AVIDIA BANK - CAPTURE CLASSIFICATION CANDIDATES

 Purpose:
   Normalize SYSTEM$CLASSIFY JSON output into candidate evidence and populate
   the steward review queue in PENDING state.

 Important:
   Candidates are machine evidence only. They are not confirmed governance
   classification and do not set GOVERNANCE.TAGS.CLASSIFICATION.
==============================================================================*/

USE ROLE DATA_GOVERNANCE_ADMIN;
USE WAREHOUSE WH_GOVERNANCE_XS;
USE DATABASE GOVERNANCE;
USE SCHEMA CATALOG;

MERGE INTO GOVERNANCE.CATALOG.CLASSIFICATION_CANDIDATE T
USING
(
    WITH FLATTENED AS
    (
        SELECT
            R.DATABASE_NAME,
            R.SCHEMA_NAME,
            R.TABLE_NAME,
            C.KEY::VARCHAR AS COLUMN_NAME,
            C.VALUE:recommendation AS RECOMMENDATION,
            C.VALUE:valid_value_ratio::FLOAT AS VALID_VALUE_RATIO,
            R.CLASSIFICATION_PROFILE,
            R.CLASSIFIED_AT
        FROM GOVERNANCE.CATALOG.CLASSIFICATION_RUN_RESULT R,
            LATERAL FLATTEN(INPUT => R.RUN_RESULT:classification_result) C
    )
    SELECT
        DATABASE_NAME,
        SCHEMA_NAME,
        TABLE_NAME,
        COLUMN_NAME,
        RECOMMENDATION:semantic_category::VARCHAR AS SEMANTIC_CATEGORY,
        RECOMMENDATION:privacy_category::VARCHAR AS PRIVACY_CATEGORY,
        RECOMMENDATION:confidence::VARCHAR AS CONFIDENCE,
        RECOMMENDATION:coverage::FLOAT AS COVERAGE,
        VALID_VALUE_RATIO,
        COALESCE(
            RECOMMENDATION:classifier_name::VARCHAR,
            'SNOWFLAKE_NATIVE'
        ) AS CLASSIFIER_NAME,
        CASE
            WHEN RECOMMENDATION:classifier_name IS NOT NULL
                THEN 'CUSTOM_CLASSIFIER'
            ELSE 'SNOWFLAKE_CLASSIFICATION'
        END AS DETECTION_SOURCE,
        CLASSIFICATION_PROFILE,
        CLASSIFIED_AT AS DETECTED_AT
    FROM FLATTENED
    WHERE RECOMMENDATION:semantic_category IS NOT NULL
) S
ON  T.DATABASE_NAME = S.DATABASE_NAME
AND T.SCHEMA_NAME = S.SCHEMA_NAME
AND T.TABLE_NAME = S.TABLE_NAME
AND T.COLUMN_NAME = S.COLUMN_NAME
AND T.SEMANTIC_CATEGORY = S.SEMANTIC_CATEGORY
WHEN MATCHED THEN UPDATE SET
    PRIVACY_CATEGORY = S.PRIVACY_CATEGORY,
    CONFIDENCE = S.CONFIDENCE,
    COVERAGE = S.COVERAGE,
    VALID_VALUE_RATIO = S.VALID_VALUE_RATIO,
    CLASSIFIER_NAME = S.CLASSIFIER_NAME,
    DETECTION_SOURCE = S.DETECTION_SOURCE,
    CLASSIFICATION_PROFILE = S.CLASSIFICATION_PROFILE,
    DETECTED_AT = S.DETECTED_AT,
    ACTIVE_FLAG = TRUE,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
(
    DATABASE_NAME,
    SCHEMA_NAME,
    TABLE_NAME,
    COLUMN_NAME,
    SEMANTIC_CATEGORY,
    PRIVACY_CATEGORY,
    CONFIDENCE,
    COVERAGE,
    VALID_VALUE_RATIO,
    CLASSIFIER_NAME,
    DETECTION_SOURCE,
    CLASSIFICATION_PROFILE,
    DETECTED_AT,
    ACTIVE_FLAG
)
VALUES
(
    S.DATABASE_NAME,
    S.SCHEMA_NAME,
    S.TABLE_NAME,
    S.COLUMN_NAME,
    S.SEMANTIC_CATEGORY,
    S.PRIVACY_CATEGORY,
    S.CONFIDENCE,
    S.COVERAGE,
    S.VALID_VALUE_RATIO,
    S.CLASSIFIER_NAME,
    S.DETECTION_SOURCE,
    S.CLASSIFICATION_PROFILE,
    S.DETECTED_AT,
    TRUE
);

MERGE INTO GOVERNANCE.CATALOG.CLASSIFICATION_REVIEW_QUEUE T
USING
(
    SELECT
        DATABASE_NAME,
        SCHEMA_NAME,
        TABLE_NAME,
        COLUMN_NAME,
        SEMANTIC_CATEGORY,
        PRIVACY_CATEGORY,
        CONFIDENCE,
        COVERAGE,
        DETECTION_SOURCE,
        CASE
            WHEN PRIVACY_CATEGORY IN ('IDENTIFIER', 'SENSITIVE')
                THEN 'RESTRICTED'
            ELSE 'CONFIDENTIAL'
        END AS PROPOSED_CLASSIFICATION
    FROM GOVERNANCE.CATALOG.CLASSIFICATION_CANDIDATE
    WHERE ACTIVE_FLAG = TRUE
) S
ON  T.DATABASE_NAME = S.DATABASE_NAME
AND T.SCHEMA_NAME = S.SCHEMA_NAME
AND T.TABLE_NAME = S.TABLE_NAME
AND T.COLUMN_NAME = S.COLUMN_NAME
AND T.SEMANTIC_CATEGORY = S.SEMANTIC_CATEGORY
WHEN MATCHED AND T.REVIEW_STATUS = 'PENDING' THEN UPDATE SET
    PRIVACY_CATEGORY = S.PRIVACY_CATEGORY,
    CONFIDENCE = S.CONFIDENCE,
    COVERAGE = S.COVERAGE,
    DETECTION_SOURCE = S.DETECTION_SOURCE,
    PROPOSED_CLASSIFICATION = S.PROPOSED_CLASSIFICATION,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
(
    DATABASE_NAME,
    SCHEMA_NAME,
    TABLE_NAME,
    COLUMN_NAME,
    SEMANTIC_CATEGORY,
    PRIVACY_CATEGORY,
    CONFIDENCE,
    COVERAGE,
    DETECTION_SOURCE,
    PROPOSED_CLASSIFICATION,
    REVIEW_STATUS
)
VALUES
(
    S.DATABASE_NAME,
    S.SCHEMA_NAME,
    S.TABLE_NAME,
    S.COLUMN_NAME,
    S.SEMANTIC_CATEGORY,
    S.PRIVACY_CATEGORY,
    S.CONFIDENCE,
    S.COVERAGE,
    S.DETECTION_SOURCE,
    S.PROPOSED_CLASSIFICATION,
    'PENDING'
);

SELECT
    REVIEW_ID,
    DATABASE_NAME,
    SCHEMA_NAME,
    TABLE_NAME,
    COLUMN_NAME,
    SEMANTIC_CATEGORY,
    PRIVACY_CATEGORY,
    PROPOSED_CLASSIFICATION,
    REVIEW_STATUS
FROM GOVERNANCE.CATALOG.CLASSIFICATION_REVIEW_QUEUE
ORDER BY
    REVIEW_STATUS,
    TABLE_NAME,
    COLUMN_NAME;
