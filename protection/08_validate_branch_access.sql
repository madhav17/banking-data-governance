/*==============================================================================
 AVIDIA BANK - VALIDATE BRANCH ROW ACCESS
==============================================================================*/

USE WAREHOUSE WH_GOVERNANCE_XS;

USE ROLE DATA_OWNER;

SELECT
    'DATA_OWNER_RAW_ACCOUNT' AS EVIDENCE_QUERY,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT BRANCH_ID) AS DISTINCT_BRANCH_COUNT,
    LISTAGG(DISTINCT BRANCH_ID, ', ')
        WITHIN GROUP (ORDER BY BRANCH_ID) AS BRANCH_IDS
FROM RAW.BANKING.ACCOUNT;

