    'DATA_OWNER_MART_DEPOSITS_DAILY' AS EVIDENCE_QUERY,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT BRANCH_ID) AS DISTINCT_BRANCH_COUNT,
    LISTAGG(DISTINCT BRANCH_ID, ', ')
