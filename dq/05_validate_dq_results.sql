/*==============================================================================
 AVIDIA BANK - VALIDATE DQ RESULTS

 Purpose:
   Evidence that exactly six DEPOSITS_DAILY data-quality checks are attached,
   executed and persisted for the latest run.
==============================================================================*/

USE ROLE DATA_GOVERNANCE_ADMIN;
USE WAREHOUSE WH_GOVERNANCE_XS;
USE DATABASE GOVERNANCE;
USE SCHEMA DQ;

-- 1. Latest DQ run details.
WITH LATEST_RUN AS
(
    SELECT RUN_ID
    FROM GOVERNANCE.DQ.DQ_RESULT
    QUALIFY ROW_NUMBER() OVER (
        ORDER BY MEASURED_AT DESC, RECORDED_AT DESC, RUN_ID DESC
    ) = 1
)
SELECT
    R.RUN_ID,
    R.CHECK_NAME,
    R.QUALITY_DIMENSION,
    R.METRIC_DATABASE,
    R.METRIC_SCHEMA,
    R.METRIC_NAME,
    R.ARGUMENTS,
    R.METRIC_VALUE,
    R.THRESHOLD_VALUE,
    R.STATUS,
    R.EXPECTATION_EXPRESSION,
    R.MEASURED_AT,
    R.RECORDED_AT
FROM GOVERNANCE.DQ.DQ_RESULT AS R
INNER JOIN LATEST_RUN AS L
    ON R.RUN_ID = L.RUN_ID
ORDER BY R.QUALITY_DIMENSION;

-- 2. Required-dimension coverage for the latest run.
WITH REQUIRED_DIMENSIONS AS
(
    SELECT * FROM VALUES
        ('COMPLETENESS'),
        ('UNIQUENESS'),
        ('VALIDITY'),
        ('CONSISTENCY'),
        ('TIMELINESS'),
        ('ACCURACY')
        AS V(QUALITY_DIMENSION)
),

LATEST_RUN AS
(
    SELECT RUN_ID
    FROM GOVERNANCE.DQ.DQ_RESULT
    QUALIFY ROW_NUMBER() OVER (
        ORDER BY MEASURED_AT DESC, RECORDED_AT DESC, RUN_ID DESC
    ) = 1
),

LATEST_RESULTS AS
(
    SELECT R.*
    FROM GOVERNANCE.DQ.DQ_RESULT AS R
    INNER JOIN LATEST_RUN AS L
        ON R.RUN_ID = L.RUN_ID
)
SELECT
    D.QUALITY_DIMENSION,
    COUNT(R.CHECK_NAME) AS CHECK_COUNT,
    MAX(R.STATUS) AS STATUS,
    MAX(R.METRIC_VALUE) AS METRIC_VALUE,
    MAX(R.THRESHOLD_VALUE) AS THRESHOLD_VALUE,
    IFF(COUNT(R.CHECK_NAME) = 1, 'PASS', 'FAIL') AS DIMENSION_PRESENT_STATUS
FROM REQUIRED_DIMENSIONS AS D
LEFT JOIN LATEST_RESULTS AS R
    ON D.QUALITY_DIMENSION = R.QUALITY_DIMENSION
GROUP BY D.QUALITY_DIMENSION
ORDER BY D.QUALITY_DIMENSION;

-- 3. Latest overall quality status.
WITH LATEST_RUN AS
(
    SELECT RUN_ID
    FROM GOVERNANCE.DQ.DQ_RESULT
    QUALIFY ROW_NUMBER() OVER (
        ORDER BY MEASURED_AT DESC, RECORDED_AT DESC, RUN_ID DESC
    ) = 1
),

LATEST_RESULTS AS
(
    SELECT R.*
    FROM GOVERNANCE.DQ.DQ_RESULT AS R
    INNER JOIN LATEST_RUN AS L
        ON R.RUN_ID = L.RUN_ID
)
SELECT
    RUN_ID,
    COUNT(*) AS TOTAL_CHECKS,
    COUNT_IF(STATUS = 'PASS') AS PASSED_CHECKS,
    COUNT_IF(STATUS = 'FAIL') AS FAILED_CHECKS,
    IFF(
        COUNT(*) = 6
        AND COUNT_IF(STATUS = 'FAIL') = 0,
        'PASS',
        'FAIL'
    ) AS OVERALL_STATUS
FROM LATEST_RESULTS
GROUP BY RUN_ID;

-- 4. Prove that the six DMFs are attached to DEPOSITS_DAILY.
SELECT
    METRIC_DATABASE_NAME,
    METRIC_SCHEMA_NAME,
    METRIC_NAME,
    REF_ENTITY_DATABASE_NAME,
    REF_ENTITY_SCHEMA_NAME,
    REF_ENTITY_NAME,
    REF_ARGUMENTS,
    SCHEDULE,
    USE_ROLE
FROM TABLE
(
    ANALYTICS.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES
    (
        REF_ENTITY_NAME => 'ANALYTICS.MARTS.DEPOSITS_DAILY',
        REF_ENTITY_DOMAIN => 'TABLE'
    )
)
WHERE METRIC_NAME IN
(
    'NULL_COUNT',
    'DUPLICATE_COUNT',
    'ACCEPTED_VALUES',
    'REFERENTIAL_INTEGRITY_COUNT',
    'DMF_LATEST_BUSINESS_DATE_MATCH',
    'DMF_GL_DEPOSIT_RECONCILIATION'
)
ORDER BY
    METRIC_DATABASE_NAME,
    METRIC_SCHEMA_NAME,
    METRIC_NAME;

