SELECT
    'CUSTOMER_360' AS MART,
    TAG_NAME,
    TAG_VALUE,
    APPLY_METHOD,
    LEVEL
FROM TABLE
(
    ANALYTICS.INFORMATION_SCHEMA.TAG_REFERENCES
    (
        'ANALYTICS.MARTS.CUSTOMER_360',
        'TABLE'
    )
)

UNION ALL

SELECT
    'DEPOSITS_DAILY',
    TAG_NAME,
    TAG_VALUE,
    APPLY_METHOD,
    LEVEL
FROM TABLE
(
    ANALYTICS.INFORMATION_SCHEMA.TAG_REFERENCES
    (
        'ANALYTICS.MARTS.DEPOSITS_DAILY',
        'TABLE'
    )
)

UNION ALL

SELECT
    'LOAN_PORTFOLIO',
    TAG_NAME,
    TAG_VALUE,
    APPLY_METHOD,
    LEVEL
FROM TABLE
(
    ANALYTICS.INFORMATION_SCHEMA.TAG_REFERENCES
    (
        'ANALYTICS.MARTS.LOAN_PORTFOLIO',
        'TABLE'
    )
)

ORDER BY
    MART,
    TAG_NAME;